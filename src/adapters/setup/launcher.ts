import { NODE_FLOOR } from '../check-node';
import { shellQuote } from './command';

/**
 * Where a launcher looks for Node. Each string is a script fragment in the syntax of its platform.
 * `files` and `system` are tried in order. The first one that passes wins.
 * `globs` are tried in order. The first glob that has a passing node wins. Inside that glob, the last
 * passing node wins, because the newest version name sorts last.
 */
export interface NodeCandidates { files: string[]; globs: string[]; system: string[] }

const POSIX_CANDIDATES: NodeCandidates = {
  files: [
    '${FNM_DIR:+"$FNM_DIR/aliases/default/bin/node"}',
    '"${XDG_DATA_HOME:-$HOME/.local/share}/fnm/aliases/default/bin/node"',
    '"$HOME/Library/Application Support/fnm/aliases/default/bin/node"',
    '"$HOME/.fnm/aliases/default/bin/node"',
    '"${VOLTA_HOME:-$HOME/.volta}/bin/node"',
  ],
  globs: [
    '"${NVM_DIR:-$HOME/.nvm}"/versions/node/*/bin/node',
    '${FNM_DIR:+"$FNM_DIR"/node-versions/*/installation/bin/node}',
    '"${XDG_DATA_HOME:-$HOME/.local/share}/fnm"/node-versions/*/installation/bin/node',
    '"$HOME/Library/Application Support/fnm"/node-versions/*/installation/bin/node',
    '"$HOME/.fnm"/node-versions/*/installation/bin/node',
    '"${VOLTA_HOME:-$HOME/.volta}"/tools/image/node/*/bin/node',
    '"${ASDF_DATA_DIR:-$HOME/.asdf}"/installs/nodejs/*/bin/node',
    '"${MISE_DATA_DIR:-${XDG_DATA_HOME:-$HOME/.local/share}/mise}"/installs/node/*/bin/node',
    '"${NODENV_ROOT:-$HOME/.nodenv}"/versions/*/bin/node',
    '"${N_PREFIX:-/usr/local}"/n/versions/node/*/bin/node',
    // Keg-only Homebrew node@NN formulas have no link in bin.
    '/opt/homebrew/opt/node@*/bin/node',
    '/usr/local/opt/node@*/bin/node',
    '/home/linuxbrew/.linuxbrew/opt/node@*/bin/node',
  ],
  // The Homebrew opt path of each prefix comes first. It follows "brew upgrade node" and it stays
  // when "brew unlink node" removes the bin link.
  system: [
    '/opt/homebrew/opt/node/bin/node',
    '/opt/homebrew/bin/node',
    '/usr/local/opt/node/bin/node',
    '/usr/local/bin/node',
    '/home/linuxbrew/.linuxbrew/opt/node/bin/node',
    '/home/linuxbrew/.linuxbrew/bin/node',
    '/usr/bin/node',
    '/snap/bin/node',
  ],
};

const LAUNCH_UNSAFE = /[%^&|<>!"()@\r\n]/;

/**
 * The Node probe as JavaScript. It loads node:sqlite, so a Node build without that module fails it.
 * `quote` is the string quote for the JS text, which depends on the shell that holds the probe.
 */
export function probeSource(quote: '"' | "'"): string {
  const { major, minor } = NODE_FLOOR;
  const js =
    `var v=process.versions.node.split(".").map(Number);` +
    `if(!(v[0]>${major}||(v[0]===${major}&&v[1]>=${minor})))process.exit(1);require("node:sqlite")`;
  return quote === '"' ? js : js.replace(/"/g, quote);
}

export const FLOOR_TEXT = `${NODE_FLOOR.major}.${NODE_FLOOR.minor}`;
const NO_NODE_MESSAGE =
  `found no Node.js ${FLOOR_TEXT} or newer with the node:sqlite module. ` +
  `Install Node.js ${FLOOR_TEXT} or newer. Then run "gournal setup claude" in a terminal.`;

export function renderPosixLauncher(o: { home: string; bakeHome: boolean; candidates?: NodeCandidates }): string {
  const c = o.candidates ?? POSIX_CANDIDATES;
  const home = shellQuote(o.home);
  const loop = (words: string[], body: string): string[] => (words.length === 0 ? [] : [`for n in ${words.join(' ')}; do ${body}; done`]);
  return [
    '#!/bin/sh',
    '# Generated by gournal setup claude. Do not edit. Setup and upgrades rewrite this file.',
    `home=${home}`,
    ...(o.bakeHome ? [`[ -n "\${GOURNAL_HOME+x}" ] || { GOURNAL_HOME=${home}; export GOURNAL_HOME; }`] : []),
    'first=${1-}',
    `quit() { [ "$first" = hook ] && exit 0; printf 'gournal: %s\\n' "$1" >&2; exit 1; }`,
    // The installed package wins. The copy runs only when the source is gone.
    'src=; { IFS= read -r src < "$home/runtime/source"; } 2>/dev/null',
    'app=; { IFS= read -r app < "$home/runtime/current"; } 2>/dev/null',
    'dir=; if [ -n "$src" ] && [ -f "$src/dist/cli.js" ]; then dir=$src; ' +
      'elif [ -n "$app" ] && [ -f "$home/runtime/$app/dist/cli.js" ]; then dir=$home/runtime/$app; fi',
    '[ -n "$dir" ] || quit "the launcher cannot find gournal in ${src:+$src or in }${home}/runtime. ' +
      'Run \\"gournal setup claude\\" in a terminal, or run \\"claude mcp remove --scope user gournal\\" to remove gournal from Claude Code."',
    `ok() { case $1 in /*) ;; *) return 1 ;; esac; [ -f "$1" ] && [ -x "$1" ] && { "$1" -e '${probeSource('"')}' </dev/null >/dev/null 2>&1; } 2>/dev/null; }`,
    'pick=; rec=; { IFS= read -r rec < "$home/runtime/node"; } 2>/dev/null',
    '[ -n "$rec" ] && ok "$rec" && pick=$rec',
    // Walk PATH by hand. Only an absolute entry counts. Some sh builds turn a relative entry
    // such as "." into an absolute path in command -v, which would run a file from the project folder.
    '[ -n "$pick" ] || { oldifs=$IFS; IFS=:; set -f; for d in $PATH; do case $d in /*) [ -z "$pick" ] && ok "$d/node" && pick=$d/node ;; esac; done; set +f; IFS=$oldifs; }',
    ...loop(c.files, '[ -z "$pick" ] && ok "$n" && pick=$n'),
    ...c.globs.map((g) => `if [ -z "$pick" ]; then for n in ${g}; do ok "$n" && pick=$n; done; fi`),
    ...loop(c.system, '[ -z "$pick" ] && ok "$n" && pick=$n'),
    `[ -n "$pick" ] || quit "${NO_NODE_MESSAGE.replace(/"/g, '\\"')}"`,
    'if [ "$pick" != "$rec" ]; then printf \'%s\\n\' "$pick" > "$home/runtime/node.$$" 2>/dev/null && ' +
      '/bin/mv -f "$home/runtime/node.$$" "$home/runtime/node" 2>/dev/null || /bin/rm -f "$home/runtime/node.$$" 2>/dev/null; fi',
    'exec "$pick" "$dir/dist/cli.js" "$@"',
    '',
  ].join('\n');
}

export function launcherCommand(launcher: string, platform: NodeJS.Platform, cmdExe: string): { command: string; args: string[] } {
  // No /s: without /s, cmd keeps the two quotes around a path with a space.
  return platform === 'win32' ? { command: cmdExe, args: ['/d', '/c', launcher] } : { command: launcher, args: [] };
}

export function checkLauncherPath(launcher: string, platform: NodeJS.Platform): string | null {
  if (platform !== 'win32' || !LAUNCH_UNSAFE.test(launcher)) return null;
  return `Launcher: cannot start ${launcher} through cmd.exe: the path holds one of % ^ & | < > ! " ( ) @. Set GOURNAL_HOME to a folder without these characters and run setup again.`;
}
