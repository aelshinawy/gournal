import { FLOOR_TEXT, probeSource, type NodeCandidates } from './launcher';

export const WINDOWS_CANDIDATES: NodeCandidates = {
  files: [
    '"%NVM_SYMLINK%\\node.exe"',
    '"%ProgramFiles%\\nodejs\\node.exe"',
    '"%FNM_DIR%\\aliases\\default\\node.exe"',
    '"%APPDATA%\\fnm\\aliases\\default\\node.exe"',
    '"%ProgramFiles%\\Volta\\node.exe"',
    '"%USERPROFILE%\\scoop\\apps\\nodejs\\current\\node.exe"',
    '"%USERPROFILE%\\scoop\\apps\\nodejs-lts\\current\\node.exe"',
  ],
  // Each entry is a folder glob. The leaf file is added by globLeaf.
  globs: [
    '"%NVM_HOME%\\v*"',
    '"%LOCALAPPDATA%\\nvm\\v*"',
    '"%APPDATA%\\nvm\\v*"',
    '"%FNM_DIR%\\node-versions\\*"',
    '"%APPDATA%\\fnm\\node-versions\\*"',
    '"%LOCALAPPDATA%\\Volta\\tools\\image\\node\\*"',
  ],
  system: [],
};

function globLeaf(glob: string): string {
  return glob.includes('node-versions') ? 'installation\\node.exe' : 'node.exe';
}

/** Render the cmd.exe launcher (CRLF line ends). It finds Node at run time. */
export function renderWindowsLauncher(o: { bakeHome: boolean; candidates?: NodeCandidates }): string {
  const c = o.candidates ?? WINDOWS_CANDIDATES;
  const probe = (set: string): string => `"%~1" -e "${probeSource("'")}" >nul 2>&1 <nul && set "${set}=%~1"`;
  const noApp = 'the launcher cannot find its copy of gournal in %GH%\\runtime. Run "gournal setup claude" in a terminal.';
  const noNode = `found no Node.js ${FLOOR_TEXT} or newer with the node:sqlite module. Install Node.js ${FLOOR_TEXT} or newer. Then run "gournal setup claude" in a terminal.`;
  return [
    '@echo off',
    'setlocal EnableExtensions DisableDelayedExpansion',
    'rem Generated by gournal setup claude. Do not edit. Setup and upgrades rewrite this file.',
    'for %%I in ("%~dp0..") do set "GH=%%~fI"',
    ...(o.bakeHome ? ['if not defined GOURNAL_HOME set "GOURNAL_HOME=%GH%"'] : []),
    'set "FIRST=%~1"',
    'set "APP="',
    'set "REC="',
    'set "PICK="',
    'set "GPICK="',
    `set "MSG=${noApp}"`,
    'if exist "%GH%\\runtime\\current" set /p APP=<"%GH%\\runtime\\current"',
    'if not defined APP goto :quit',
    'if not exist "%GH%\\runtime\\%APP%\\dist\\cli.js" goto :quit',
    `set "MSG=${noNode}"`,
    'if exist "%GH%\\runtime\\node" set /p REC=<"%GH%\\runtime\\node"',
    'if defined REC call :try "%REC%"',
    // where.exe searches the current folder first, and it turns a relative PATH entry into an
    // absolute path. :trywhere skips every result under the current folder.
    'set "CDP=%CD%"',
    'if not "%CDP:~-1%"=="\\" set "CDP=%CDP%\\"',
    `for /f "delims=" %%N in ('where node 2^>nul') do call :trywhere "%%N"`,
    ...c.files.map((f) => `call :try ${f}`),
    ...c.globs.map((g) => `if not defined PICK if not defined GPICK for /d %%D in (${g}) do call :tryall "%%D\\${globLeaf(g)}"`),
    'if not defined PICK if defined GPICK set "PICK=%GPICK%"',
    ...c.system.map((f) => `call :try ${f}`),
    'if not defined PICK goto :quit',
    'if /i not "%PICK%"=="%REC%" <nul set /p "=%PICK%" >"%GH%\\runtime\\node.tmp"',
    'move /y "%GH%\\runtime\\node.tmp" "%GH%\\runtime\\node" >nul 2>&1',
    '"%PICK%" "%GH%\\runtime\\%APP%\\dist\\cli.js" %* & exit /b',
    ':quit',
    'if /i "%FIRST%"=="hook" exit 0',
    '1>&2 echo gournal: %MSG%',
    'exit 1',
    ':trywhere',
    'if /i "%~dp1"=="%CDP%" exit /b',
    // At a drive root every path is under the current folder, so only the root folder itself is skipped.
    'if "%CDP:~3%"=="" goto :trywhere_go',
    'set "R=%~1"',
    'call set "REST=%%R:%CDP%=%%"',
    'if /i "%CDP%%REST%"=="%R%" exit /b',
    ':trywhere_go',
    'call :try "%~1"',
    'exit /b',
    ':try',
    'if defined PICK exit /b',
    'if "%~1"=="" exit /b',
    'if not exist "%~1" exit /b',
    probe('PICK'),
    'exit /b',
    ':tryall',
    'if "%~1"=="" exit /b',
    'if not exist "%~1" exit /b',
    probe('GPICK'),
    'exit /b',
    '',
  ].join('\r\n');
}
