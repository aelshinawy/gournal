// ---- MCP tool reference ----
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { InMemoryTransport } from '@modelcontextprotocol/sdk/inMemory.js';
import { createDocsServer, schemaRows } from '../site/scripts/reference/mcp';

describe('MCP reference', () => {
  const toolNames = async (): Promise<string[]> => {
    const { server } = createDocsServer();
    const [ct, st] = InMemoryTransport.createLinkedPair();
    const c = new Client({ name: 'docs-test', version: '0.0.0' });
    await Promise.all([c.connect(ct), server.connect(st)]);
    try { return (await c.listTools()).tools.map((t) => t.name).sort(); } finally { await c.close(); await server.close(); }
  };

  test('every MCP tool has a page', async () => {
    const names = await toolNames();
    expect(names).toHaveLength(12);
    const pages = await generateReference({ examplesDir });
    for (const n of names) {
      expect(pages.filter((p) => new RegExp(`^### ${n}$`, 'm').test(p.content))).toHaveLength(1);
    }
    expect(pages.map((p) => p.path)).toContain('output-shapes.md');
    expect(pages.map((p) => p.path)).not.toContain('mcp/output-shapes.md');
  });

  test('input tables list every field with its required flag', async () => {
    const add = await get('add.md');
    expect(add).toContain('### add_entry');
    expect(add).toContain('#### Input');
    expect(add).toMatch(/^\| `summary` \| `string` \| no \|/m);
    expect(add).toMatch(/^\| `refs` \| `object\[\]` \| no \|/m);
    expect(add).toMatch(/^\| `refs.type` \| `"pr" \\\| "jira" \\\| "commit" \\\| "url"` \| yes \|/m);
    expect(add).toMatch(/^\| `refs.value` \| `string` \| yes \|/m);
    expect(add).toMatch(/^\| `tags` \| `string\[\]` \| no \|/m);
    expect(schemaRows({ type: 'object', required: ['a'], properties: { a: { type: 'string', description: 'x|y' }, b: { type: ['integer', 'null'] } } } as never))
      .toEqual([['`a`', '`string`', 'yes', 'x|y'], ['`b`', '`integer | null`', 'no', '']]);
  });

  test('shared output shapes appear once and tool sections link to them', async () => {
    const shapes = await get('output-shapes.md');
    for (const h of ['Activity', 'Entry', 'Entry list', 'Entry result']) {
      expect(shapes.match(new RegExp(`^## ${h}$`, 'gm'))).toHaveLength(1);
    }
    const link = '/gournal/docs/reference/output-shapes/#entry-result';
    for (const c of ['add.md', 'edit.md']) {
      const page = await get(c);
      expect(page).toContain(link);
      expect(page).not.toContain('| `entry` |');
    }
    expect(await get('list.md')).toContain('/gournal/docs/reference/output-shapes/#entry-list');
    // The Entry shape has its own fields. The entry-result shape holds one row that links to it.
    expect(shapes).toMatch(/^\| `deviceId` \| `string` \| yes \|/m);
    expect(shapes).toContain('[`Entry`](/gournal/docs/reference/output-shapes/#entry)');
    // A tool with no outputSchema says it returns text.
    expect(await get('export.md')).toContain('returns text content');
  });

  test('get_standup output links to the Entry shape and has no deviceId row', async () => {
    const standup = await get('standup.md');
    expect(standup).toContain('#### Output');
    expect(standup).toContain('/gournal/docs/reference/output-shapes/#entry');
    expect(standup).toContain('/gournal/docs/reference/output-shapes/#activity');
    expect(standup).not.toContain('deviceId');
    expect(standup).not.toContain('`done.entries.id`');
  });

  test('the MCP server used for docs touches no real home', async () => {
    const before = fs.readdirSync(process.env.HOME as string).sort();
    const { server, touched } = createDocsServer();
    const [ct, st] = InMemoryTransport.createLinkedPair();
    const c = new Client({ name: 'docs-test', version: '0.0.0' });
    await Promise.all([c.connect(ct), server.connect(st)]);
    await c.listTools();
    await c.close();
    await server.close();
    expect(touched()).toBe(false);
    await generateReference({ examplesDir });
    expect(fs.readdirSync(process.env.HOME as string).sort()).toEqual(before);
    expect(fs.existsSync(path.join(process.env.HOME as string, '.gournal'))).toBe(false);
  });
});

test('every MCP field row has a description', async () => {
  const pages = (await generateReference({ examplesDir })).filter((p) => p.content.includes('\n## MCP tool\n'));
  expect(pages.length).toBeGreaterThan(0);
  const empty: string[] = [];
  for (const p of pages) {
    const mcpPart = p.content.split('\n## MCP tool\n')[1].split(/\n## /)[0];
    for (const line of mcpPart.split('\n')) {
      const cells = line.split(/(?<!\\)\|/).map((c) => c.trim());
      // A field row starts with a code-quoted name. The description is the last cell before the closing pipe.
      if (cells.length < 5 || !cells[1]?.startsWith('`')) continue;
      if (cells[cells.length - 2] === '') empty.push(`${p.path}: ${cells[1]}`);
    }
  }
  expect(empty).toEqual([]);
});

import { Command } from 'commander';
import { inertProgram } from '../site/scripts/reference/generate';
import { leafNames, cliSection } from '../site/scripts/reference/cli';
import { listTools } from '../site/scripts/reference/mcp';
import { CAPABILITIES, GROUPS, checkCoverage } from '../site/scripts/reference/capabilities';

describe('capability registry', () => {
  test('every CLI leaf and MCP tool maps to exactly one capability', async () => {
    const cli = leafNames(inertProgram());
    const mcp = (await listTools()).map((t) => t.name);
    expect(cli.length).toBeGreaterThan(0);
    expect(mcp.length).toBeGreaterThan(0);
    expect(checkCoverage(cli, mcp)).toEqual([]);
  });

  test('checkCoverage names an unmapped command and the file to edit', () => {
    const problems = checkCoverage(['add', 'brand-new'], ['add_entry', 'new_tool']);
    const text = problems.join('\n');
    expect(text).toContain('brand-new');
    expect(text).toContain('new_tool');
    expect(text).toContain('site/scripts/reference/capabilities.ts');
  });

  test('checkCoverage names a command mapped twice', () => {
    const dup = [...CAPABILITIES, { ...CAPABILITIES[0], slug: 'dup-add' }];
    const problems = checkCoverage(['add'], ['add_entry'], dup);
    expect(problems.join('\n')).toMatch(/add.*(twice|more than one)/);
  });

  test('capability slugs are unique and do not clash with configuration, environment, output-shapes, or index', () => {
    const slugs = CAPABILITIES.map((c) => c.slug);
    expect(new Set(slugs).size).toBe(slugs.length);
    for (const reserved of ['configuration', 'environment', 'output-shapes', 'index']) {
      expect(slugs).not.toContain(reserved);
    }
    const groupIds = GROUPS.map((g) => g.id);
    for (const c of CAPABILITIES) expect(groupIds).toContain(c.group);
  });

  test('related entries point to a capability or an existing guide', () => {
    const slugs = new Set(CAPABILITIES.map((c) => c.slug));
    for (const c of CAPABILITIES) {
      expect(c.related.length).toBeGreaterThanOrEqual(1);
      for (const r of c.related) {
        if (r.startsWith('guides/')) {
          expect(fs.existsSync(path.join(siteRoot, 'src/content/docs/docs', `${r}.md`))).toBe(true);
        } else {
          expect(slugs.has(r)).toBe(true);
        }
      }
    }
  });
});

