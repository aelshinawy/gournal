test('examples are inlined, and a removed command loses its page and an orphan example fails', async () => {
  const tmp = makeTmp('docs-ref-site-');
  try {
    const refDir = path.join(tmp, REFERENCE_DIR);
    fs.mkdirSync(path.join(refDir, 'cli'), { recursive: true });
    fs.mkdirSync(path.join(tmp, 'src/content/examples/cli'), { recursive: true });
    fs.writeFileSync(path.join(refDir, 'cli/nope.md'), 'stale\n');
    fs.writeFileSync(path.join(tmp, 'src/content/examples/cli/nope.md'), 'orphan\n');
    fs.writeFileSync(path.join(tmp, 'src/content/examples/cli/undo.md'), '```bash\ngournal undo\n```\n');
    const { deleted, written } = await writeReference(tmp);
    expect(deleted).toEqual(['cli/nope.md']);
    expect(fs.existsSync(path.join(refDir, 'cli/nope.md'))).toBe(false);
    expect(fs.existsSync(path.join(refDir, 'cli'))).toBe(false);
    expect(written).toContain('add.md');
    expect(fs.readFileSync(path.join(refDir, 'remove-restore.md'), 'utf8')).toContain('## Examples\n\n### CLI\n\n#### gournal undo\n\n```bash\ngournal undo\n```\n');
    expect(await orphanExamples(path.join(tmp, 'src/content/examples'))).toEqual(['cli/nope.md']);
    expect(await orphanExamples(examplesDir)).toEqual([]);
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
});

