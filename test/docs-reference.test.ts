import fs from 'fs';
import os from 'os';
import path from 'path';
import { CONFIG_KEY_DOCS, ENV_VAR_DOCS } from '../src/core';
import {
  generateReference, orphanExamples, ownedFilesOnDisk, writeReference, REFERENCE_DIR,
} from '../site/scripts/reference/generate';
import { table } from '../site/scripts/reference/markdown';

const siteRoot = path.resolve(__dirname, '../site');
const examplesDir = path.join(siteRoot, 'src/content/examples');
const referenceDir = path.join(siteRoot, REFERENCE_DIR);
const EM_DASH = String.fromCharCode(0x2014);

const get = async (p: string): Promise<string> => {
  const page = (await generateReference({ examplesDir })).find((x) => x.path === p);
  if (!page) throw new Error(`No page ${p}`);
  return page.content;
};

test('the committed reference is current', async () => {
  const pages = await generateReference({ examplesDir });
  const stale = 'Reference is stale. Run: npm run docs:gen';
  for (const p of pages) {
    const file = path.join(referenceDir, p.path);
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== p.content) throw new Error(stale);
  }
  const expected = pages.map((p) => p.path).sort();
  // Extra files in owned paths fail too.
  const onDisk = ownedFilesOnDisk(referenceDir);
  if (JSON.stringify(onDisk) !== JSON.stringify(expected)) throw new Error(stale);
});

test('generation is deterministic', async () => {
  const a = await generateReference({ examplesDir });
  const b = await generateReference({ examplesDir });
  expect(b).toEqual(a);
  expect(a.map((p) => p.path)).toEqual(a.map((p) => p.path).slice().sort());
  for (const p of a) {
    expect(p.content.endsWith('\n')).toBe(true);
    expect(p.content.endsWith('\n\n')).toBe(false);
    expect(p.content).not.toContain('\r');
  }
});

test('cli pages show arguments, short flags, and defaults exactly', async () => {
  const add = await get('cli/add.md');
  expect(add).toContain('    gournal add <summary> [options]');
  expect(add).toContain('| `-t, --tags <tags>` | Tag the entry. Separate tags with commas. | (empty) |');
  expect(add).toContain('title: gournal add\n');
  expect(add).toContain('description: Add a journal entry.\n');
  expect(add).toContain('<!-- Generated by npm run docs:gen. Do not edit. Edit examples in site/src/content/examples/cli/add.md. -->');
  expect(add).toContain('## Examples');
  // A command with no options has no [options] and no table.
  const undo = await get('cli/undo.md');
  expect(undo).toContain('    gournal undo\n');
  expect(undo).not.toContain('## Options');
  expect(undo).not.toContain('## Examples');
  // A quoted description is safe YAML.
  expect(await get('cli/standup.md')).toMatch(/^description: Show a standup report for today, or for the period that you choose\.$/m);
  expect(await get('mcp/sync_activity.md')).toMatch(/^description: "Fetch the user's GitHub activity \(PRs, commits, reviews\) through the gh CLI, and link it to journal entries\."$/m);
});

test('hidden commands get no page', async () => {
  const paths = (await generateReference({ examplesDir })).map((p) => p.path);
  expect(paths).not.toContain('cli/hook-stop.md');
  expect(paths.some((p) => p.includes('hook'))).toBe(false);
});

test('subcommands join with a hyphen and group parents get no page', async () => {
  const paths = (await generateReference({ examplesDir })).map((p) => p.path);
  expect(paths).toContain('cli/setup-claude.md');
  expect(paths).toContain('cli/index-rebuild.md');
  expect(paths).not.toContain('cli/index.md');
  expect(paths).not.toContain('cli/setup.md');
  expect(await get('cli/index-rebuild.md')).toContain('    gournal index rebuild\n');
});

test('building the program does not open the journal', async () => {
  const home = fs.mkdtempSync(path.join(os.tmpdir(), 'docs-ref-'));
  const before = process.env.GOURNAL_HOME;
  process.env.GOURNAL_HOME = path.join(home, 'never');
  try {
    await generateReference({ examplesDir });
    expect(fs.existsSync(path.join(home, 'never'))).toBe(false);
  } finally {
    process.env.GOURNAL_HOME = before;
    fs.rmSync(home, { recursive: true, force: true });
  }
});

test('examples are inlined, and a removed command loses its page and an orphan example fails', async () => {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'docs-ref-site-'));
  try {
    const refDir = path.join(tmp, REFERENCE_DIR);
    fs.mkdirSync(path.join(refDir, 'cli'), { recursive: true });
    fs.mkdirSync(path.join(tmp, 'src/content/examples/cli'), { recursive: true });
    fs.writeFileSync(path.join(refDir, 'cli/nope.md'), 'stale\n');
    fs.writeFileSync(path.join(tmp, 'src/content/examples/cli/nope.md'), 'orphan\n');
    fs.writeFileSync(path.join(tmp, 'src/content/examples/cli/undo.md'), '```bash\ngournal undo\n```\n');
    const { deleted, written } = await writeReference(tmp);
    expect(deleted).toEqual(['cli/nope.md']);
    expect(fs.existsSync(path.join(refDir, 'cli/nope.md'))).toBe(false);
    expect(written).toContain('cli/add.md');
    expect(fs.readFileSync(path.join(refDir, 'cli/undo.md'), 'utf8')).toContain('## Examples\n\n```bash\ngournal undo\n```\n');
    const pages = await generateReference({ examplesDir: path.join(tmp, 'src/content/examples') });
    expect(orphanExamples(pages, path.join(tmp, 'src/content/examples'))).toEqual(['cli/nope.md']);
    expect(orphanExamples(pages, examplesDir)).toEqual([]);
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
});

test('configuration and environment pages list every descriptor', async () => {
  const config = await get('configuration.md');
  for (const k of CONFIG_KEY_DOCS) {
    expect(config).toContain(`\`${k.key}\``);
    expect(config).toContain(k.type.replace(/\|/g, '\\|'));
    if (k.validation) expect(config).toContain(k.validation.replace(/\|/g, '\\|'));
  }
  const env = await get('environment.md');
  for (const v of ENV_VAR_DOCS) {
    expect(env).toContain(`\`${v.name}\``);
    expect(env).toContain(v.description);
  }
  expect(config).toContain('Generated by npm run docs:gen. Do not edit.');
  expect(env).toContain('Generated by npm run docs:gen. Do not edit.');
});

