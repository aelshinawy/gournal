// Small Markdown helpers for the reference generator. Output is byte-stable.

/** Escape text for one table cell: pipes and line breaks would break the row. */
function cell(text: string): string {
  return text.replace(/\\/g, '\\\\').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
}

/** Render a Markdown table. Every cell is escaped. */
export function table(headers: string[], rows: string[][]): string {
  const line = (cols: string[]): string => `| ${cols.map(cell).join(' | ')} |`;
  const rule = `|${headers.map((h) => '-'.repeat(Math.max(3, h.length + 2))).join('|')}|`;
  return [line(headers), rule, ...rows.map(line)].join('\n');
}

/** Wrap text in backticks, using a longer fence when the text holds a backtick. */
export function code(text: string): string {
  const fence = text.includes('`') ? '``' : '`';
  const pad = text.startsWith('`') || text.endsWith('`') ? ' ' : '';
  return `${fence}${pad}${text}${pad}${fence}`;
}

/** Quote a YAML scalar only when a bare scalar would be unsafe. */
function yamlString(value: string): string {
  return /^[A-Za-z0-9][A-Za-z0-9 ,.()/_-]*$/.test(value) && !/\s$/.test(value) ? value : JSON.stringify(value);
}

export function frontmatter(title: string, description: string): string {
  return `---\ntitle: ${yamlString(title)}\ndescription: ${yamlString(description)}\n---\n`;
}

/** The first sentence of a description. */
export function firstSentence(text: string): string {
  const match = /^.*?[.!?](?=\s|$)/s.exec(text.trim());
  return (match ? match[0] : text.trim()).replace(/\s+/g, ' ');
}

